def t_mu(out: Path, T: Path, rep: Report):
    rep.h("C1 — penalty selection")
    runs = rd(out / "mu" / "runs.csv")
    if not runs:
        rep.add("mu", "MISSING — run `python 05_mu_selection_sweep.py`")
        return
    extra = rd(out / "mu_rules" / "runs.csv")
    if not extra:
        rep.add("mu-rules", "MISSING — run `python 05b_mu_rules_sweep.py` (Mag-IL / Diag-x over the same grid)")
    runs = runs + extra
    rows = []
    for ds in sorted({r["dataset"] for r in runs}):
        for R0 in sorted({int(r["rank_init"]) for r in runs if r["dataset"] == ds}):
            for meth in ("ES", "SA", "Mag-IL", "Diag-x"):
                prof = rank_profile(runs, ds, meth, R0)
                if not prof:
                    continue
                pl = widest_plateau(prof, exclude_full=R0)
                rt = prof[0]["rank_true"]
                ex_at = next((p["exact"] for p in prof if pl and math.isclose(p["mu"], pl["mu_mid"])), float("nan"))
                rows.append([esc(ds), f"\\({R0}\\)", meth, f"\\({pl.get('rank', '--')}\\)" if pl else "--",
                             f"\\([{pl['mu_lo']:g}, {pl['mu_hi']:g}]\\)" if pl else "--",
                             pct(pl.get("stability", float('nan')), 0) if pl else "--",
                             f"\\({rt}\\)" if rt != "" else "--", pct(ex_at, 0)])
                rep.add(f"{ds} | R_max={R0} | {meth} plateau",
                        (f"rank {pl['rank']} over mu in [{pl['mu_lo']:g}, {pl['mu_hi']:g}] ({pl['width']} grid points, "
                         f"stability {100 * pl['stability']:.0f}%), exact recovery at plateau centre {100 * ex_at:.0f}%")
                        if pl else "no stable plateau")
                top = max(int(r["rank_init"]) for r in runs if r["dataset"] == ds and r["method"] in ("ES", "Mag-IL"))
                if meth in ("ES", "Mag-IL", "Diag-x") and R0 == top and rt != "":
                    for p in prof:
                        rep.add(f"{ds} | R_max={R0} | {meth} | mu={p['mu']:g}",
                                f"mean rank {p['mean']:.2f} ± {p['std']:.2f}, exact {100 * p['exact']:.0f}%")
                    best = max(prof, key=lambda p: p["exact"])
                    rep.add(f"{ds} | R_max={R0} | {meth} | best over the grid",
                            f"exact {100 * best['exact']:.0f}% at mu={best['mu']:g}; mu values with exact >= 90%: "
                            f"{sum(p['exact'] >= 0.9 for p in prof)} of {len(prof)}")
        # full distribution for the figure
    write_tex(T / "tableC1_plateaus.tex",
              ["Dataset", "\\(R_{\\max}\\)", "Solver", "Plateau \\(\\hat R\\)", "\\(\\mu\\) range", "Stability",
               "\\(R_{\\mathrm{true}}\\)", "Exact at centre"], rows, "Penalty plateaus (C1)")
    # long-format distribution for plotting
    dist = defaultdict(lambda: defaultdict(int))
    for r in runs:
        if r["method"] == "ES":
            dist[(r["dataset"], int(r["rank_init"]), f(r["mu"]))][int(r["final_rank"])] += 1
    with open(T / "figC1_rank_distribution.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["dataset", "rank_init", "mu", "rank", "count"])
        for (ds, R0, mu), d in sorted(dist.items()):
            for k, v in sorted(d.items()):
                w.writerow([ds, R0, mu, k, v])


def t_sigma(out: Path, T: Path, rep: Report):
    rep.h("C1 — noise-calibrated starting penalty")
    mu0 = rd(out / "sigma" / "mu0.csv")
    runs = [r for r in rd(out / "sigma" / "runs.csv") if r["method"] == "ES"]
    if not mu0 or not runs:
        rep.add("sigma", "MISSING — run `python 06_mu_sigma_rule.py`")
        return
    rows, score = [], defaultdict(list)
    for m in mu0:
        rr = [r for r in runs if r["dataset"] == m["dataset"] and r.get("tag") == f"beta={float(m['beta'])}"]
        rk = [int(r["final_rank"]) for r in rr]
        ex = np.mean([f(r["exact_rank"]) for r in rr]) if rr and rr[0].get("exact_rank") not in ("", None) else float("nan")
        if np.isfinite(ex):
            score[float(m["beta"])].append(ex)
        rows.append([esc(m["dataset"]), f"\\({float(m['beta']):g}\\)", fmt(f(m["sigma_hat"]), d=3),
                     fmt(f(m["sigma_true"]), d=3) if m["sigma_true"] else "--", fmt(f(m["mu0"]), d=3),
                     fmt(*mean_std(rk), d=3), pct(ex, 0)])
        rep.add(f"{m['dataset']} | kappa={m['beta']}", f"sigma_hat {f(m['sigma_hat']):.3g} (true {m['sigma_true'] or 'n/a'}), "
                f"mu0 {f(m['mu0']):.3g}, rank {np.mean(rk) if rk else float('nan'):.2f}, exact {100 * ex:.0f}%")
    if score:
        best = max(score, key=lambda b: np.mean(score[b]))
        rep.add("kappa with the best mean exact recovery on the synthetic designs",
                f"{best:g} ({100 * np.mean(score[best]):.0f}% averaged over {len(score[best])} designs)")
    write_tex(T / "tableC1_sigma_rule.tex", ["Dataset", "\\(\\kappa\\)", "\\(\\hat\\sigma\\)", "\\(\\sigma\\)", "\\(\\mu_0\\)",
                                             "\\(\\hat R\\)", "Exact"], rows, "Noise-calibrated penalty (C1)")


