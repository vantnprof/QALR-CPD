def rd(path: Path) -> List[Dict]:
    if not path.exists():
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def f(x) -> float:
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def _num(v, d=4):
    if v == 0:
        return "0"
    if 1e-3 <= abs(v) < 1e4:
        return f"{v:.{d}g}"
    e = int(math.floor(math.log10(abs(v))))
    return f"{v / 10 ** e:.{max(d - 1, 1)}f}{{\\times}}10^{{{e}}}"


def fmt(m, s=None, d=4):
    if not np.isfinite(m):
        return "--"
    if s is None or not np.isfinite(s):
        return f"\\({_num(m, d)}\\)"
    return f"\\({_num(m, d)} \\pm {_num(s, d)}\\)"


def esc(t) -> str:
    """Escape free text (dataset and method names) for LaTeX cells."""
    t = str(t)
    for a, b in (("\\", "\\textbackslash{}"), ("_", "\\_"), ("%", "\\%"), ("#", "\\#"), ("&", "\\&"), ("$", "\\$")):
        t = t.replace(a, b)
    return t


def pct(x, d=1):
    return "--" if not np.isfinite(x) else f"{100 * x:.{d}f}\\%"


class Report:
    def __init__(self):
        self.lines: List[str] = []

    def h(self, t):
        self.lines += ["", f"## {t}", ""]

    def add(self, key, val):
        self.lines.append(f"- **{key}**: {val}")

    def note(self, t):
        self.lines.append(f"  _{t}_")

    def text(self):
        return "\n".join(["# Values for the response-letter placeholders",
                          "", "Generated by `python 14_make_tables.py`. Every value comes from revision_out/; "
                          "a missing stage is marked MISSING."] + self.lines) + "\n"


def write_tex(path: Path, header: List[str], rows: List[List[str]], caption: str):
    cols = "l" + "c" * (len(header) - 1)
    # longtable so that long tables break across pages (needs \\usepackage{longtable}; not inside a float)
    body = [f"% {caption}", f"\\begin{{longtable}}{{@{{}}{cols}@{{}}}}", "\\toprule", " & ".join(header) + " \\\\",
            "\\midrule", "\\endhead"] + [" & ".join(r) + " \\\\" for r in rows] + ["\\bottomrule", "\\end{longtable}"]
    path.write_text("\n".join(body) + "\n")


def group(runs, keys):
    g = defaultdict(list)
    for r in runs:
        g[tuple(r[k] for k in keys)].append(r)
    return g


