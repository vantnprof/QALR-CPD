def t_hardware(out: Path, T: Path, rep: Report):
    rep.h("R3.2 — repeated hardware runs")
    rows_in = rd(out / "hardware" / "hardware_repeats.csv")
    if not rows_in:
        rep.add("hardware", "MISSING — run `python 13_ibm_hardware_repeats.py` (see README)")
        return
    for (inst, proto, be), g in group(rows_in, ["instance", "protocol", "backend"]).items():
        gm, gs = mean_std([r["gap_pct"] for r in g])
        pm, ps = mean_std([r["p_shot_opt"] for r in g])
        hit = np.mean([f(r["hit"]) for r in g])
        rep.add(f"{be} | {proto} | {inst}",
                f"{len(g)} repeats: gap {gm:.3g}% ± {gs:.2g}, P(opt) per shot {pm:.4f} ± {ps:.2g} "
                f"(simulator {f(g[0]['sim_p_shot_opt']):.4f}), optimum returned {100 * hit:.0f}%, depth {g[0]['isa_depth']}, "
                f"two-qubit gates {g[0]['two_qubit_gates']}, SWAPs {g[0]['swaps_routing']}, QPU s/run {np.nanmean([f(r['qpu_seconds']) for r in g]):.3g}, "
                f"job ids in hardware_repeats.csv")


def t_profile(out: Path, T: Path, rep: Report):
    rep.h("R4.5 / R5.4 — cost of one pruning call (Table 17)")
    calls = rd(out / "profile" / "calls.csv")
    if not calls:
        rep.add("profile", "MISSING — run `python 15_runtime_profile.py`")
        return
    rows = []
    for first in (True, False):
        sel = [c for c in calls if (int(f(c["R_before"])) == int(f(c["rank_init"]))) == first]
        label = "first call (R = R_max)" if first else "later calls (R < R_max)"
        if not sel:
            continue
        qb = [f(c.get("qubo_build_s", "")) for c in sel]
        qb = [x for x in qb if np.isfinite(x)]
        if qb:
            rep.add(f"{label} | QUBO construction", f"{np.mean(qb):.3g} s mean, {np.median(qb):.3g} s median, n={len(qb)}")
            rows.append([label, "QUBO construction", _num(np.mean(qb), 3), _num(np.median(qb), 3), str(len(qb))])
        for m in ("ES", "BF", "MS-BF", "SA", "Tabu", "QAOA"):
            t = [f(c["solver_time_s"]) for c in sel if c["method"] == m]
            if t:
                rep.add(f"{label} | {m} solve", f"{np.mean(t):.3g} s mean, {np.median(t):.3g} s median, n={len(t)}")
                rows.append([label, f"{m} solve", _num(np.mean(t), 3), _num(np.median(t), 3), str(len(t))])
        q = [c for c in sel if c["method"] == "QAOA"]
        for k in ("t_transpile_s", "t_optimize_s", "t_sample_s", "t_select_s", "n_estimator_evals"):
            v = [f(c.get(k, "")) for c in q]
            v = [x for x in v if np.isfinite(x)]
            if v:
                rep.add(f"{label} | QAOA {k}", f"{np.mean(v):.3g} mean, {np.median(v):.3g} median, n={len(v)}")
                rows.append([label, f"QAOA {k.replace('_', ' ')}", _num(np.mean(v), 3), _num(np.median(v), 3), str(len(v))])
        by_ds = defaultdict(list)
        for c in q:
            by_ds[c["dataset"]].append(f(c["solver_time_s"]))
        for ds, v in sorted(by_ds.items()):
            rep.add(f"{label} | QAOA solve | {ds}", f"{np.mean(v):.3g} s mean, n={len(v)}")
    write_tex(T / "tableR4-5_runtime.tex", ["Calls", "Step", "Mean (s)", "Median (s)", "\\(n\\)"], rows,
              "Cost of one pruning call")


